// Bridge between the editor and the main process. Runs sandboxed: only these narrow
// functions are exposed; the page never sees Node, Electron or file paths.
'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');
const invoke = (ch, ...a) => ipcRenderer.invoke(ch, ...a);

contextBridge.exposeInMainWorld('reel', {
  sandboxed: process.sandboxed === true,
  recent: () => invoke('projects:recent'),
  projectClose: token => invoke('project:close', token),
  projectForget: key => invoke('project:forget', key),
  projectReveal: key => invoke('project:revealKey', key),
  projectTrash: key => invoke('project:trash', key),
  projectRename: (key, name) => invoke('project:rename', key, name),
  projectDuplicate: key => invoke('project:duplicate', key),
  create: name => invoke('project:create', name),
  openRecent: key => invoke('project:openRecent', key),
  openDialog: () => invoke('project:openDialog'),
  save: (token, doc, poster) => invoke('project:save', token, doc, poster),
  reveal: token => invoke('project:reveal', token),
  importMedia: token => invoke('media:import', token),
  // files → their locations on disk; read at once, during the drop (the browser empties a drop's file list afterwards)
  pathsOf: files => Array.from(files || [], f => { try { return webUtils.getPathForFile(f); } catch { return ''; } }).filter(Boolean),
  // one File at a time: a single File crosses into this preload reliably (a whole FileList may not)
  pathOf: f => { try { return webUtils.getPathForFile(f) || ''; } catch { return ''; } },
  importDropped: (token, filesOrPaths) => invoke('media:importDropped', token, Array.isArray(filesOrPaths) ? filesOrPaths : Array.from(filesOrPaths, f => webUtils.getPathForFile(f)).filter(Boolean)),
  readJson: (token, name) => invoke('media:readJson', token, name),
  writeJson: (token, stem, data) => invoke('media:writeJson', token, stem, data),
  importPaths: (token, paths) => invoke('media:importPaths', token, paths),
  copyIn: (token, src) => invoke('media:copyIn', token, src),
  deleteMedia: (token, name) => invoke('media:delete', token, name),
  revealMedia: (token, name) => invoke('media:reveal', token, name),
  archiveProject: (token, onlyUsed) => invoke('project:archive', token, onlyUsed),
  templateSave: (token, name) => invoke('template:save', token, name),
  templateList: () => invoke('template:list'),
  templateUse: id => invoke('template:use', id),
  templateRemove: id => invoke('template:remove', id),
  replaceMedia: (token, kind) => invoke('media:replace', token, kind),
  globalList: () => invoke('global:list'),
  globalAdd: (token, name, label) => invoke('global:add', token, name, label),
  globalImport: (token, file) => invoke('global:import', token, file),
  globalRemove: file => invoke('global:remove', file),
  globalReveal: () => invoke('global:reveal'),
  permissions: () => invoke('rec:permissions'),
  machineInfo: () => invoke('machine:info'),
  fixRange: (token, file) => invoke('media:fixRange', token, file),
  setTheme: choice => invoke('theme:set', choice),
  storageGet: () => invoke('storage:get'),
  speechTranscribe: (token, file, from, to, locale, jobId) => invoke('speech:transcribe', token, file, from, to, locale, jobId),
  speechCancel: jobId => invoke('speech:cancel', jobId),
  onSpeechProgress: fn => ipcRenderer.on('speech:progress', (_e, id, m) => fn(id, m)),
  storageChoose: () => invoke('storage:choose'),
  storageReset: () => invoke('storage:reset'),
  storageReveal: () => invoke('storage:reveal'),
  cacheInfo: token => invoke('cache:info', token),
  cacheClearProxies: token => invoke('cache:clearProxies', token),
  askAccess: kind => invoke('rec:askAccess', kind),
  aiWriterStatus: () => invoke('ai:writerStatus'),
  aiWriterSetup: key => invoke('ai:writerSetup', key),
  aiWriterSetupCancel: () => invoke('ai:writerSetupCancel'),
  aiWrite: req => invoke('ai:write', req),
  recDiscard: (ids, seconds) => invoke('rec:discard', ids, seconds),
  openPrivacy: kind => invoke('rec:openPrivacy', kind),
  sources: () => invoke('rec:sources'),
  selectSource: (id, systemAudio) => invoke('rec:select', id, systemAudio),
  recBegin: (token, tracks, apps, input) => invoke('rec:begin', token, tracks, apps, input),
  recChunk: (id, data) => ipcRenderer.send('rec:chunk', id, data),
  recEnd: (ids, meta) => invoke('rec:end', ids, meta),
  recCancel: ids => invoke('rec:cancel', ids),
  recPause: paused => invoke('rec:pause', paused),
  shortcutsGet: () => invoke('shortcuts:get'),
  shortcutsSet: own => invoke('shortcuts:set', own),
  shortcutsCapture: on => invoke('shortcuts:capture', on),
  hideWindow: () => invoke('rec:hideWindow'),
  exportBegin: (token, name, kind) => invoke('export:begin', token, name, kind),
  exportPickFolder: () => invoke('export:pickFolder'),
  exportBeginIn: (token, folderId, name, kind) => invoke('export:beginIn', token, folderId, name, kind),
  exportChunk: (id, data) => ipcRenderer.send('export:chunk', id, data),
  exportFinish: (id, head) => invoke('export:finish', id, head),
  exportCancel: id => invoke('export:cancel', id),
  exportReveal: name => invoke('export:reveal', name),
  saveThumbnail: (token, bytes, name) => invoke('thumb:save', token, bytes, name),
  audioAvailable: () => invoke('audio:available'),
  audioList: () => invoke('audio:list'),
  audioSet: (key, rule) => invoke('audio:set', key, rule),
  audioReset: () => invoke('audio:reset'),
  audioMeter: on => invoke('audio:meter', on),
  onAudioLevels: cb => ipcRenderer.on('audio-levels', (_e, l) => cb(l)),
  onImportProgress: cb => ipcRenderer.on('import-progress', (_e, p) => cb(p)),
  fxAvailable: () => invoke('fx:available'),
  fxPlugins: () => invoke('fx:plugins'),
  fxVst3: () => invoke('fx:vst3'),
  fxEdit: (slot, plugin, state, title) => invoke('fx:edit', slot, plugin, state, title),
  fxEditClose: slot => invoke('fx:editClose', slot),
  setUndoLabels: (undo, redo) => invoke('menu:undoLabels', undo, redo),
  fxState: slot => invoke('fx:state', slot),
  fxSource: (token, media) => invoke('fx:source', token, media),
  fxUpBegin: (token, purpose, media, channels) => invoke('fx:upBegin', token, purpose, media, channels),
  fxChunk: (id, data) => ipcRenderer.send('fx:chunk', id, data),
  fxUpEnd: id => invoke('fx:upEnd', id),
  fxRender: (token, job) => invoke('fx:render', token, job),
  fxPreviewVoice: (token, source, params, start, seconds) => invoke('fx:previewVoice', token, source, params, start, seconds),
  fxPreviewPlugins: (token, source, slots, start, seconds, device, gain) => invoke('fx:previewPlugins', token, source, slots, start, seconds, device, gain),
  fxPreviewStop: () => invoke('fx:previewStop'),
  fxRenderFile: (token, source, chain) => invoke('fx:renderFile', token, source, chain),
  fxRemoveTemp: (token, name) => invoke('fx:removeTemp', token, name),
  onFxEdited: cb => ipcRenderer.on('fx-edited', (_e, m) => cb(m)),
  onFxProgress: cb => ipcRenderer.on('fx-progress', (_e, m) => cb(m)),
  saveStill: (token, png, label) => invoke('media:saveStill', token, png, label),
  renderBegin: (token, label, ext) => invoke('media:renderBegin', token, label, ext),
  renderChunk: (id, data) => ipcRenderer.send('media:renderChunk', id, data),
  renderFinish: (id, head) => invoke('media:renderFinish', id, head),
  renderCancel: id => invoke('media:renderCancel', id),
  saveFrame: (token, png, name) => invoke('still:save', token, png, name),
  captionsOpen: () => invoke('captions:open'),
  captionsSave: (text, name, kind) => invoke('captions:save', text, name, kind),
  captionsBeside: (name, text) => invoke('captions:beside', name, text),
  matteMake: (token, media, quality) => invoke('matte:make', token, media, quality),
  onMatteProgress: cb => ipcRenderer.on('matte-progress', (_e, v) => cb(v)),
  lutImport: token => invoke('lut:import', token),
  ttsVoices: () => invoke('tts:voices'),
  ttsMake: (token, text, voice, rate) => invoke('tts:make', token, text, voice, rate),
  kittenStatus: () => invoke('kitten:status'),
  kittenSetup: () => invoke('kitten:setup'),
  kittenSetupCancel: () => invoke('kitten:setupCancel'),
  kittenRemove: () => invoke('kitten:remove'),
  kittenSay: (token, req) => invoke('kitten:say', token, req),
  kittenCancel: () => invoke('kitten:cancel'),
  kittenSaveVoice: (name, samples, rate, text) => invoke('kitten:saveVoice', name, samples, rate, text),
  kittenDeleteVoice: id => invoke('kitten:deleteVoice', id),
  aiStatus: () => invoke('ai:status'),
  aiGenerate: (token, job) => invoke('ai:generate', token, job),
  aiCancel: () => invoke('ai:cancel'),
  aiLoras: engine => invoke('ai:loras', engine),
  aiFluxSetup: opts => invoke('ai:fluxSetup', opts),
  aiFluxSetupCancel: () => invoke('ai:fluxSetupCancel'),
  aiSaveImage: (token, png, label) => invoke('ai:saveImage', token, png, label),
  aiSuggest: req => invoke('ai:suggest', req),
  onAi: cb => ipcRenderer.on('ai-event', (_e, ev) => cb(ev)),
  onOpenProject: cb => ipcRenderer.on('open-project', (_e, p) => cb(p)),
  onMenu: cb => ipcRenderer.on('menu', (_e, cmd) => cb(cmd)),
  setDirty: d => ipcRenderer.send('dirty', !!d),
  closeNow: () => invoke('window:closeNow'),
});
